def clean_text(text: str) -> list:
    """
    Очищает текст от пунктуации и приводит к нижнему регистру,
    разбивая его на отдельные слова.
    """
    # 1. Приводим к нижнему регистру
    text = text.lower()
    
    # 2. Заменяем русские кавычки и тире на стандартные пробелы или удаляем
    text = text.replace('«', ' ').replace('»', ' ').replace('—', ' ').replace('–', ' ')
    
    # 3. Удаляем всю стандартную пунктуацию (.,!?;:"'()[]{} и т.д.)
    # string.punctuation содержит: !"#$%&'()*+,-./:;<=>?@[\]^_`{|}~
    translator = str.maketrans('', '', string.punctuation)
    text = text.translate(translator)
    
    # 4. Разбиваем на слова и убираем пустые строки
    words = text.split()
    
    return words

def calculate_water_percentage(text: str) -> float:
    """
    Рассчитывает процент "водности" текста.
    """
    words = clean_text(text)
    if not words:
        return 0.0
    
    total_words = len(words)
    stop_words_count = sum(1 for word in words if word in STOP_WORDS_RU)
    
    # Формула: (стоп-слова / общее количество слов) * 100
    water_percentage = (stop_words_count / total_words) * 100
    return round(water_percentage, 2)

